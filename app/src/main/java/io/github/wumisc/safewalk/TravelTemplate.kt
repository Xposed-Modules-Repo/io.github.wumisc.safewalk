package io.github.wumisc.safewalk

/**
 * 4 套出行模板（求职 / 约会 / 聚会 / 旅游），本地纯文本。
 */
object TravelTemplate {
    fun getTemplate(mode: String): List<String> = when (mode) {
        "求职" -> listOf(
            "优先青旅，只订1晚，现场看房",
            "精简行李，面试仅带小包",
            "每日预算定额，公交优先，留应急金",
            "出发前电话确认面试信息",
            "证件拍照备份，原件贴身存放"
        )
        "约会" -> listOf(
            "提前沟通双方喜好，选交通方便地",
            "提前出门，预留堵车缓冲时间",
            "不打探收入、感情过往等隐私",
            "提前商量 AA 或轮流买单",
            "尊重对方边界，不强行肢体接触"
        )
        "聚会" -> listOf(
            "尽量准时，迟到提前告知众人",
            "不强行劝酒，量力饮酒",
            "提前约定 AA 制，结束统一结算",
            "不随意评判他人，不打探隐私",
            "离场前打招呼，确认返程安全"
        )
        "旅游" -> listOf(
            "住宿多看实拍评价，优先可退订单",
            "精简行李，大件可车站寄存",
            "提前规划预算，预留应急资金",
            "离线地图，提前查交通班次",
            "证件拍照存档，贵重物品贴身"
        )
        else -> emptyList()
    }

    /**
     * 「到场提示」：真正到某类场所时才推，所以只留**当下这一刻用得上**的礼节，
     * 不再混进「优先青旅只订1晚」这类出发前的行程准备。
     *
     * 原来的做法是直接取 [getTemplate] 的前 3 条拼成一大段，于是到站收到的
     * 通知是「优先青旅，只订1晚，现场看房；精简行李，面试仅带小包；每日预算定额…」
     * ——既跟地点无关，也不是到场该看的。两套内容因此拆开。
     */
    fun getArrivalTips(mode: String): List<String> = when (mode) {
        "求职" -> listOf(
            "进门先在访客机登记、出示身份证",
            "手机调静音，称呼用「姓+职位」，等对方先伸手再握手"
        )
        "约会" -> listOf(
            "到了先找好位置并告知对方，别让人干等",
            "不打探收入与感情过往，买单主动开口 AA"
        )
        "聚会" -> listOf(
            "先跟主人和长辈打招呼，再找位置坐",
            "不强行劝酒，离开前说一声并确认返程"
        )
        "旅游" -> listOf(
            "证件与贵重物品贴身，人多处背包前置",
            "记下住宿地址与前台电话，押金票据收好"
        )
        else -> emptyList()
    }
}
